#include <stdint.h>
#include <stdio.h>
#include <string.h>

static const uint8_t blob[] = {
    0x29,0x3f,0x28,0x2c,0x3f,0x28,0x67,0x3e,0x3f,0x37,0x35,0x74,0x33,0x34,0x2c,0x3b,0x36,0x33,0x3e,
    0x61,0x37,0x35,0x3e,0x3f,0x67,0x28,0x3f,0x2a,0x35,0x28,0x2e,0x61
};

static void decode(char *out)
{
    size_t i;
    for (i = 0; i < sizeof blob; ++i)
        out[i] = (char)(blob[i] ^ 0x5au);
    out[sizeof blob] = 0;
}

int main(void)
{
    char out[sizeof blob + 1];
    decode(out);
    puts(out);
    return strcmp(out, "server=demo.invalid;mode=report;") != 0;
}
